#!/usr/bin/env python3
"""Generate js/midi/mapping.js from a Mixxx Pioneer DDJ-*.midi.xml preset."""
import os
import sys
import xml.etree.ElementTree as ET

DEFAULT_XML = "/usr/share/mixxx/controllers/Pioneer DDJ-SX.midi.xml"

# Mixxx script-binding key suffix -> app action (None = drop)
DECK_ACT = {
    "playButton": "play",
    "cueButton": "cue",
    "syncButton": "sync",
    "shiftButton": "shift",
    "loadButton": "load",
    "reverseButton": "reverse",
    "keyLockButton": "keylock",
    "vinylButton": "vinyl",
    "slipButton": "slip",
    "loopInButton": "loopIn",
    "loopOutButton": "loopOut",
    "loopExitButton": "loopExit",
    "loopHalveButton": "loopHalve",
    "loopDoubleButton": "loopDouble",
    "autoLoopButton": "autoLoop",
    "quantizeButton": "quantize",
    "tempoSliderMSB": "tempo", "tempoSliderLSB": "tempo@lsb",
    "deckFaderMSB": "vol", "deckFaderLSB": "vol@lsb",
    "gainKnobMSB": "gain", "gainKnobLSB": "gain@lsb",
    "filterHighKnobMSB": "hi", "filterHighKnobLSB": "hi@lsb",
    "filterMidKnobMSB": "mid", "filterMidKnobLSB": "mid@lsb",
    "filterLowKnobMSB": "low", "filterLowKnobLSB": "low@lsb",
    "filterKnobMSB": "deckfilter", "filterKnobLSB": "deckfilter@lsb",
    "needleSearchStripPosition": "needle",
    "jogPlatterTick": "jogTick",
    "jogTouch": "jogTouch",
    "jogRingTick": "jogRing",
    "crossfaderAssignLeft": "xfAssign", "crossfaderAssignRight": "xfAssign",
    "crossfaderAssignCenter": "xfAssign",
}
MASTER_ACT = {
    "crossFaderMSB": "crossfader", "crossFaderLSB": "crossfader@lsb",
    "crossfaderCurveKnobMSB": "xfCurve", "crossfaderCurveKnobLSB": "xfCurve@lsb",
}
# pad ranges on status 0x97 (per-deck pad channel)
PAD_INDEXED = {
    "hotCueButtons": (0x00, 0x0F, "hotcue"),      # 0..7 set, 8..15 shift-clear
    "beatloopButtons": (0x50, 0x57, "beatloop"),  # sizes: 1/2,1,2,4,8,16,32,64
}


def gen(xml_path):
    root = ET.parse(xml_path).getroot()
    entries = []
    for c in root.iter("control"):
        group = c.findtext("group") or ""
        key = (c.findtext("key") or "").split(".")[-1]
        status = int(c.findtext("status"), 16)
        d1 = int(c.findtext("midino"), 16)
        shifted = False
        name = key
        if name.startswith("shift") and len(name) > 5 and name[5].isupper():
            shifted = True
            name = name[5].lower() + name[6:]
        act = idx = None
        if group.startswith("[Channel"):
            deck = int(group[len("[Channel"):-1]) - 1
            if deck >= 4:
                continue
            if name in PAD_INDEXED:
                lo, hi, act = PAD_INDEXED[name]
                if not (lo <= d1 <= hi):
                    continue
                idx = d1 - lo
            else:
                act = DECK_ACT.get(name)
            if act is None:
                continue
            if name == "crossfaderAssignLeft":
                idx = 0
            elif name == "crossfaderAssignRight":
                idx = 1
            elif name == "crossfaderAssignCenter":
                idx = 2
        elif group == "[Master]":
            deck = -1
            act = MASTER_ACT.get(name)
            if act is None:
                continue
        else:
            continue  # FX units, samplers, library, autodj: v1 drop
        e = {"s": status, "d": d1, "a": act, "deck": deck}
        if idx:
            e["i"] = idx
        if shifted:
            e["f"] = 1
        entries.append(e)
    entries.sort(key=lambda e: (e["deck"], e["s"], e["d"]))

    lines = [
        "// AUTO-GENERATED by tools/gen-mapping.py from",
        "//   %s" % xml_path,
        "// Do not edit by hand; regenerate or use js/midi/mapping-override.json.",
        "export const MAPPING = [",
    ]
    for e in entries:
        parts = ["s:0x%02X" % e["s"], "d:0x%02X" % e["d"], "a:%r" % e["a"], "deck:%d" % e["deck"]]
        if e.get("i"):
            parts.append("i:%d" % e["i"])
        if e.get("f"):
            parts.append("f:1")
        lines.append("  {" + ",".join(parts) + "},")
    lines.append("];")
    return "\n".join(lines) + "\n", len(entries)


if __name__ == "__main__":
    xml = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_XML
    out = os.path.join(os.path.dirname(__file__), "..", "js", "midi", "mapping.js")
    src, n = gen(xml)
    with open(out, "w") as fh:
        fh.write(src)
    print("wrote %s (%d entries)" % (os.path.normpath(out), n))
